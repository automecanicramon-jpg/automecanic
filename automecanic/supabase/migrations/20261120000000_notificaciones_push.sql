  ON public.push_subscription;
CREATE POLICY "push_subscription_select_own"
  ON public.push_subscription
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.usuario AS u
      WHERE u.id_usuario = push_subscription.id_usuario
        AND u.auth_id = (SELECT auth.uid())
        AND u.estatus = 'Activo'
