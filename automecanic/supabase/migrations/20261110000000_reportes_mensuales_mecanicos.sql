ALTER TABLE public.reporte_generado
  ADD COLUMN IF NOT EXISTS id_mecanico integer,
  ADD COLUMN IF NOT EXISTS id_vehiculo integer,
  ADD COLUMN IF NOT EXISTS generado_automaticamente boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.reporte_entrega_mensual (
  id_entrega bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  anio integer NOT NULL,
  estado text NOT NULL DEFAULT 'PENDIENTE',
  notificaciones_creadas boolean NOT NULL DEFAULT false,
  correos_enviados boolean NOT NULL DEFAULT false,
  total_reportes integer NOT NULL DEFAULT 0,
  ultimo_error text,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reporte_entrega_mensual_periodo_key UNIQUE (mes, anio)
);

ALTER TABLE public.reporte_entrega_mensual ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.reporte_entrega_mensual TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.reporte_entrega_mensual_id_entrega_seq TO service_role;

CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS vault;
CREATE EXTENSION IF NOT EXISTS supabase_vault WITH SCHEMA vault;

DO $$
DECLARE
  v_existing_job_id bigint;
BEGIN
  SELECT jobid
  INTO v_existing_job_id
  FROM cron.job
  WHERE jobname = 'generar-reportes-mensuales-mecanicos';

  IF v_existing_job_id IS NOT NULL THEN
    PERFORM cron.unschedule(v_existing_job_id);
  END IF;

  PERFORM cron.schedule(
    'generar-reportes-mensuales-mecanicos',
    '0 14 1 * *',
    $job$
      SELECT net.http_post(
        url := 'https://noqknvwnejvauxzsbdsy.supabase.co/functions/v1/generar-reportes-mensuales',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'Authorization', 'Bearer ' || (
            SELECT decrypted_secret
            FROM vault.decrypted_secrets
            WHERE name = 'automecanic_service_role_key'
          ),
          'apikey', (
            SELECT decrypted_secret
            FROM vault.decrypted_secrets
            WHERE name = 'automecanic_service_role_key'
          )
        ),
        body := jsonb_build_object('scheduled', true)
      );
    $job$
  );
END;
$$;
