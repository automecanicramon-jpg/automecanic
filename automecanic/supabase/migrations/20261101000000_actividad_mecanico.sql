CREATE TABLE IF NOT EXISTS public.actividad_mecanico (
  id_actividad bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_mecanico bigint NOT NULL,
  tipo_accion text NOT NULL,
  modulo text NOT NULL,
  descripcion text NOT NULL,
  referencia_id bigint,
  fecha_registro timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.actividad_mecanico ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.actividad_mecanico TO authenticated;

CREATE OR REPLACE FUNCTION public.usuario_es_administrador_actual()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
SET row_security = off
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.usuario AS u
    WHERE u.auth_id = (SELECT auth.uid())
      AND u.id_rol = 1
  );
$$;

REVOKE ALL ON FUNCTION public.usuario_es_administrador_actual() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.usuario_es_administrador_actual() TO authenticated;

DROP POLICY IF EXISTS "admin_select_mechanic_activity"
  ON public.actividad_mecanico;
CREATE POLICY "admin_select_mechanic_activity"
  ON public.actividad_mecanico
  FOR SELECT
  TO authenticated
  USING (public.usuario_es_administrador_actual());

CREATE INDEX IF NOT EXISTS actividad_mecanico_fecha_registro_idx
  ON public.actividad_mecanico (fecha_registro DESC);

CREATE INDEX IF NOT EXISTS actividad_mecanico_mecanico_idx
  ON public.actividad_mecanico (id_mecanico);
