CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS vault;
CREATE EXTENSION IF NOT EXISTS supabase_vault WITH SCHEMA vault;

CREATE OR REPLACE FUNCTION public.enviar_notificacion_push_alerta()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, vault, extensions
AS $$
DECLARE
  v_service_role_key text;
BEGIN
  IF NEW.id_usuario IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT decrypted_secret
  INTO v_service_role_key
  FROM vault.decrypted_secrets
  WHERE name = 'automecanic_service_role_key'
  LIMIT 1;

  IF NULLIF(v_service_role_key, '') IS NULL THEN
    RAISE WARNING 'No se envió notificación push: falta el secreto Vault automecanic_service_role_key.';
    RETURN NEW;
  END IF;

  PERFORM net.http_post(
    url := 'https://noqknvwnejvauxzsbdsy.supabase.co/functions/v1/send-push-notification',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || v_service_role_key,
      'apikey', v_service_role_key
    ),
    body := jsonb_build_object(
      'id_alerta', NEW.id_alerta
    )
  );

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.enviar_notificacion_push_alerta() FROM PUBLIC;

DROP TRIGGER IF EXISTS enviar_notificacion_push_alerta
  ON public.alerta;
CREATE TRIGGER enviar_notificacion_push_alerta
  AFTER INSERT ON public.alerta
  FOR EACH ROW
  EXECUTE FUNCTION public.enviar_notificacion_push_alerta();
