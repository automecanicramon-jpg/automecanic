CREATE TABLE IF NOT EXISTS public.push_subscription (
  id_push_subscription bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL
    REFERENCES public.usuario(id_usuario)
    ON DELETE CASCADE,
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth text NOT NULL,
  fecha_registro timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT push_subscription_endpoint_key
    UNIQUE (endpoint)
);

ALTER TABLE public.push_subscription ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE public.push_subscription
  TO authenticated;
GRANT USAGE, SELECT
  ON SEQUENCE public.push_subscription_id_push_subscription_seq
  TO authenticated, service_role;
GRANT ALL
  ON TABLE public.push_subscription
  TO service_role;

